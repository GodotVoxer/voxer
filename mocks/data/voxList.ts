export const voxList: VoxListItem[] = voxListRows.map((row) => ({ ...row, pinnedAt: null }));

const youtubeIdFromListRow = (thumb: string): string => {
  const fromThumb = thumb.match(/\/vi\/([^/]+)\//)?.[1];
  if (fromThumb) return fromThumb;
  return extractYoutubeVideoId(thumb) ?? "dQw4w9WgXcQ";
};
export const getMockVoxDetail = (id: string): VoxDetail | null => {
  const row = voxList.find((v) => v.id === id);
  if (!row) return null;
  const thumb = row.thumbnailUrl ?? "";
  const demoNow = MSW_DEMO_ALWAYS_NEW_LIST_ITEM_IDS.has(row.id);
  const createdAt = demoNow ? new Date().toISOString() : "2024-06-01T12:00:00.000Z";
  if (row.mediaType === "UPLOADED_VIDEO") {
    return {
      id: row.id,
      title: row.title,
      description: "Vox de demostración con video subido (MSW).",
      category: row.category,
      mediaType: "UPLOADED_VIDEO",
      mediaUrl: "https://samplelib.com/lib/preview/mp4/sample-5s.mp4",
      thumbnailUrl: thumb,
      animatedImage: false,
      youtubeVideoId: null,
      createdAt,
      updatedAt: createdAt,
      following: false,
      hidden: false,
      favorited: row.favorited,
      isOwner: false,
      threadUniqueIdsEnabled: false,
      countryFlagsEnabled: false,
      hasPoll: row.hasPoll,
      poll: null,
    };
  }
  if (row.mediaType === "YOUTUBE") {
    const vid = youtubeIdFromListRow(thumb);
    return {
      id: row.id,
      title: row.title,
      description: "Vox de demostración con YouTube (MSW). Probá el reproductor y los comentarios.",
      category: row.category,
      mediaType: "YOUTUBE",
      mediaUrl: `https://www.youtube.com/embed/${vid}`,
      thumbnailUrl: thumb,
      animatedImage: false,
      youtubeVideoId: vid,
      createdAt,
      updatedAt: createdAt,
      following: false,
      hidden: false,
      favorited: row.favorited,
      isOwner: false,
      threadUniqueIdsEnabled: false,
      countryFlagsEnabled: false,
      hasPoll: row.hasPoll,
      poll: null,
    };
  }
  return {
    id: row.id,
    title: row.title,
    description: `Comentarios de demo para «${row.title}». Datos mockeados.`,
    category: row.category,
    mediaType: "IMAGE",
    mediaUrl: row.coverGifUrl ?? thumb,
    thumbnailUrl: thumb,
    animatedImage: false,
    youtubeVideoId: null,
    createdAt,
    updatedAt: createdAt,
    following: false,
    hidden: false,
    favorited: row.favorited,
    isOwner: false,
    threadUniqueIdsEnabled: false,
    countryFlagsEnabled: false,
    hasPoll: row.hasPoll,
    poll: null,
  };
};
